def test_reviewed_team_nicknames_are_never_a_bare_common_word():
    reviewed = json.loads((RES / "team_nicknames.json").read_text())["entries"]
    said = [norm(n) for e in reviewed for n in e["nicknames"]]
    assert not [n for n in said if n in TEAM_ABBREV_STOP or n in resolve._ENGLISH]
    # every entry finds its club in ESPN's table, and in the league's own table where there is one
    for table in ("team_espn", "team_mlb", "team_nhl"):
        leagues = {e["attrs"]["league"] for e in _rows(table)}
        for e in reviewed:
            if e["league"] in leagues:
                hit = [t for t in _rows(table)
                       if t["attrs"]["league"] == e["league"] and norm(e["club"]) in t["aliases"]]
                assert len(hit) == 1, (table, e)
                assert {norm(n) for n in e["nicknames"]} <= set(hit[0]["attrs"]["nicknames"]), (table, e)


# --- places: coast marks (resolvers._add_coast) ---------------------------------------------------------

@pytest.mark.parametrize("name,state,coastal,great_lakes", [
    ("Duluth", "GA", False, False),  # Atlanta's suburb: no marine source
    ("Duluth", "MN", False, True),  # Lake Superior, not the ocean
    ("Chicago", "IL", False, True), ("Cleveland", "OH", False, True),
    ("Nags Head", "NC", True, False), ("Cape Canaveral", "FL", True, False), ("Miami", "FL", True, False),
    ("San Francisco", "CA", True, False),  # its Census point lies out on the water
    ("Massena", "NY", False, False),  # the St. Lawrence above tide is not the ocean coast
    ("Atlanta", "GA", False, False), ("Sacramento", "CA", False, False),
])
def test_places_say_whether_they_are_on_the_ocean_coast_or_a_great_lake(name, state, coastal, great_lakes):
    p = _one("place", name=name, state=state)
    assert p["attrs"]["coastal"] is coastal
    assert p["attrs"].get("great_lakes", False) is great_lakes


def test_every_place_has_a_coast_mark_and_none_is_both():
    rows = _rows("place")
    assert all(isinstance(p["attrs"].get("coastal"), bool) for p in rows)
    assert not [p["id"] for p in rows if p["attrs"]["coastal"] and p["attrs"].get("great_lakes")]
    assert all(p["attrs"].get("great_lakes", True) is True for p in rows)  # written only when true


def test_shore_distance_and_land_test_on_a_square():
    from sourcetool.resolvers import _near_shore, _on_land, _shore_grid
    square = [[-80.0, 30.0], [-79.0, 30.0], [-79.0, 31.0], [-80.0, 31.0], [-80.0, 30.0]]
    grid = _shore_grid([square])
    assert _near_shore(grid, 30.5, -80.2, 25.0)  # ~19 km west of the edge
    assert not _near_shore(grid, 30.5, -80.5, 25.0)  # ~48 km
    assert _near_shore(grid, 30.5, -79.5, 50.0) and not _near_shore(grid, 30.5, -79.5, 25.0)  # the middle
    bands = {}
    for e in zip(square, square[1:]):
        for b in range(int(min(e[0][1], e[1][1])), int(max(e[0][1], e[1][1])) + 1):
            bands.setdefault(b, []).append(e)
    assert _on_land(bands, 30.5, -79.5) and not _on_land(bands, 30.5, -80.5)


